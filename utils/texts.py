def faq_text(items: list[tuple[str, str]]) -> str:
    result = "❓ <b>FAQ</b>\n\n"
    for idx, (q, a) in enumerate(items, 1):
        result += f"{idx}. <b>{q}</b>\n{a}\n\n"
    return result.rstrip()


